import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const source = resolve(dirname(fileURLToPath(import.meta.url)), '../dist');
const browser = await chromium.launch({
  args: ['--enable-gpu', '--enable-unsafe-swiftshader'],
});
try {
  const page = await browser.newPage();
  await page.route('http://ceramic.test/**', async (route) => {
    const { pathname } = new URL(route.request().url());
    if (pathname === '/') {
      return route.fulfill({ contentType: 'text/html', body: '<!doctype html>' });
    }
    const file = resolve(source, '.' + pathname);
    if (!file.startsWith(source + sep) || !file.endsWith('.js')) return route.abort();
    return route.fulfill({ contentType: 'text/javascript', body: await readFile(file) });
  });
  await page.goto('http://ceramic.test/');
  const assets = await page.evaluate(async () => {
    const THREE = await import('/vendor/three.module.js');
    const { ceramicCharacter, poseCeramicCharacter } = await import('/ceramic-cast.js');
    const { CHARACTERS } = await import('/content.js');
    const renderer = new THREE.WebGLRenderer({
      alpha: true,
      antialias: true,
      preserveDrawingBuffer: true,
    });
    renderer.setClearColor(0x000000, 0);
    renderer.outputColorSpace = THREE.SRGBColorSpace;
    renderer.toneMapping = THREE.ACESFilmicToneMapping;
    renderer.toneMappingExposure = 1.02;
    const scene = new THREE.Scene();
    scene.add(new THREE.HemisphereLight('#fff2d8', '#a5b09b', 1.8));
    for (const [x, y, z, color, intensity] of [
      [-3, 5, 7, '#fff4df', 3.2],
      [4, 3, -3, '#b5d7f6', 2],
    ]) {
      const light = new THREE.DirectionalLight(color, intensity);
      light.position.set(x, y, z);
      scene.add(light);
    }
    const faces = {};
    const poses = {};
    for (const { id } of CHARACTERS) {
      const model = ceramicCharacter(id);
      scene.add(model);
      poses[id] = {};
      for (const mode of ['face', 'idle', 'happy', 'sad']) {
        const face = mode === 'face';
        const size = face ? 112 : 224;
        renderer.setSize(size, size);
        poseCeramicCharacter(model, { time: 0.52, mood: mode });
        model.rotation.y = face ? -0.12 : -0.37;
        const bounds = new THREE.Box3().setFromObject(model);
        const height = bounds.max.y - bounds.min.y;
        const width = bounds.max.x - bounds.min.x;
        const center = bounds.min.y + height * (face ? 0.69 : 0.5);
        const horizontal = (bounds.max.x + bounds.min.x) / 2;
        const span = face ? Math.max(height * 0.365, width * 0.49) : Math.max(height, width) * 0.57;
        const camera = new THREE.OrthographicCamera(-span, span, span, -span, 0.1, 30);
        camera.position.set(horizontal, center + (face ? 0.08 : 0.26), 7);
        camera.lookAt(horizontal, center, 0);
        renderer.render(scene, camera);
        const url = renderer.domElement.toDataURL('image/webp', 0.86);
        if (!url.startsWith('data:image/webp;base64,')) throw new Error('WebP unavailable');
        if (face) faces[id] = url;
        else poses[id][mode] = url;
      }
      scene.remove(model);
    }
    renderer.dispose();
    return { faces, poses };
  });
  const { faces, poses } = assets;
  await writeFile(
    join(source, 'ceramic-portraits-data.js'),
    '// Generated by tools/render-ceramic-portraits.mjs.\n' +
      '// prettier-ignore\nexport const faces = ' +
      JSON.stringify(faces) +
      ';\n' +
      '// prettier-ignore\nexport const poses = ' +
      JSON.stringify(poses) +
      ';\n',
  );
} finally {
  await browser.close();
}
